/* The start of the PC port: the memory of the PlayStation at its own
 * addresses, the user's executable loaded into it, then the game's main().
 *
 * The port is a 32-bit process. The 2 MB of RAM are at 0x80000000 and the
 * scratchpad (with the I/O ports after it) at 0x1F800000, where the code of
 * the game uses them: sections of the program (tools/pc/build.py) that the
 * system maps as zeroed memory. The global variables of the C files are linked
 * at their PlayStation addresses inside the RAM (tools/pc/build.py), so
 * loading the executable gives them their initial values, and the data that
 * is not C (the data segment: tables and pointers between them) is used in
 * place. Pointers to C functions in that data are PlayStation addresses: they
 * are replaced by the addresses of the x86 functions. */
#include "types.h"

#include <errno.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define RAM_ADDR 0x80000000u
#define RAM_SIZE 0x200000u

/* generated by tools/pc/build.py */
extern const u32 pc_func_table[][2];
extern const u32 pc_func_count;
extern const u32 pc_scan_ranges[][2];
extern const u32 pc_scan_count;

s32 game_main(void); /* main() of src/main.c */

/* for the start code of PSY-Q (__SN_ENTRY_POINT) */
extern u8 D_80060A38[]; /* the start of .sbss/.bss */
extern u8 D_8006EA78[]; /* the end of .bss */
extern u32 D_8005E1A8, D_8005E1AC; /* the heap: start, size */
extern s32 _ramsize, _stacksize;
void InitHeap(void *start, u32 size); /* the game's (recompiled heap.s) */

/* as __SN_ENTRY_POINT: clears .bss, puts the heap from the end of .bss to
 * the stack at the top of the RAM */
static void psx_start(void)
{
    u32 top = (u32)_ramsize - 8;
    u32 start = (u32)D_8006EA78 & 0x1FFFFFFF;
    u32 size = top - (u32)_stacksize - start;

    memset(D_80060A38, 0, D_8006EA78 - D_80060A38);
    D_8005E1AC = size;
    D_8005E1A8 = start | RAM_ADDR;
    InitHeap((void *)((start | RAM_ADDR) + 4), size);
}

static u32 func_lookup(u32 psx)
{
    u32 lo = 0, hi = pc_func_count;

    while (lo < hi) {
        u32 mid = (lo + hi) / 2;

        if (pc_func_table[mid][0] == psx) {
            return pc_func_table[mid][1];
        }
        if (pc_func_table[mid][0] < psx) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return 0;
}

s32 pc_cd_open(const char *path);
s32 pc_cd_find(const char *name, u32 *lba, u32 *size);
s32 pc_cd_read_file(u32 lba, u32 size, void *buf);

/* the executable (a PS-X EXE) into the RAM */
static void load_exe_image(const u8 *head, const u8 *text, u32 len, const char *what)
{
    u32 t_addr, t_size;

    memcpy(&t_addr, head + 0x18, 4);
    memcpy(&t_size, head + 0x1C, 4);
    if (memcmp(head, "PS-X EXE", 8) || t_addr < RAM_ADDR || t_addr + t_size > RAM_ADDR + RAM_SIZE ||
        t_size > len) {
        fprintf(stderr, "%s: not the PlayStation executable of the game\n", what);
        exit(1);
    }
    memcpy((void *)t_addr, text, t_size);
}

static u8 *read_whole(const char *path, u32 *len)
{
    FILE *f = fopen(path, "rb");
    u8 *buf;
    long n;

    if (!f) {
        return NULL;
    }
    fseek(f, 0, SEEK_END);
    n = ftell(f);
    fseek(f, 0, SEEK_SET);
    buf = malloc(n);
    if (!buf || fread(buf, 1, n, f) != (size_t)n) {
        exit(1);
    }
    fclose(f);
    *len = (u32)n;
    return buf;
}

static void load_exe(const char *path)
{
    u32 len;
    u8 *data = read_whole(path, &len);

    if (!data || len < 0x800) {
        fprintf(stderr, "cannot read %s: %s\n", path, strerror(errno));
        exit(1);
    }
    load_exe_image(data, data + 0x800, len - 0x800, path);
    free(data);
}

/* the executable from the root of the disc */
static void load_exe_from_disc(const char *name)
{
    u32 lba, size;
    u8 *data;

    if (!pc_cd_find(name, &lba, &size) || size < 0x800 || !(data = malloc(size)) ||
        !pc_cd_read_file(lba, size, data)) {
        fprintf(stderr, "%s is not on the disc\n", name);
        exit(1);
    }
    load_exe_image(data, data + 0x800, size - 0x800, name);
    free(data);
}

static s32 is_exe(const char *path)
{
    FILE *f = fopen(path, "rb");
    char magic[8] = { 0 };

    if (!f) {
        return 0;
    }
    if (fread(magic, 1, 8, f) != 8) {
        magic[0] = 0;
    }
    fclose(f);
    return !memcmp(magic, "PS-X EXE", 8);
}

/* pointers to C functions in the data: PlayStation addresses -> x86 */
static void patch_func_pointers(void)
{
    u32 i, n = 0;

    for (i = 0; i < pc_scan_count; i++) {
        u32 *p = (u32 *)pc_scan_ranges[i][0];
        u32 *end = (u32 *)pc_scan_ranges[i][1];

        for (; p < end; p++) {
            u32 x = func_lookup(*p);

            if (x) {
                *p = x;
                n++;
            }
        }
    }
    if (getenv("PC_VERBOSE")) {
        fprintf(stderr, "port: %u pointers to C functions in the data\n", n);
    }
}

/* the recompiled code calls a C function: by its x86 address, or by the
 * PlayStation address of a C function of the game */
u32 rc_ext_call(u32 pc, u32 a0, u32 a1, u32 a2, u32 a3)
{
    u32 x = pc >= RAM_ADDR && pc < RAM_ADDR + RAM_SIZE ? func_lookup(pc) : pc;

    if (!x) {
        fprintf(stderr, "port: the recompiled code calls %08X, which is no C function\n", pc);
        abort();
    }
    return ((u32(*)(u32, u32, u32, u32))x)(a0, a1, a2, a3);
}

/* the recompiled nd_asm: break, syscall, an unknown instruction */
void rc_trap(u32 addr, u32 what)
{
    fprintf(stderr, "port: trap at %08X (%08X) in the recompiled code\n", addr, what);
    abort();
}

static void usage(void)
{
    fprintf(stderr, "usage: crash3 DISC [EXE]\n"
                    "  DISC: an image of your Crash Bandicoot 3 disc (.cue, .bin or .iso)\n"
                    "  EXE:  its executable, when not the one on the disc (SCUS_942.44)\n"
                    "or: crash3 EXE (no disc: the game stops at the first read)\n");
    exit(1);
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        usage();
    }
    if (is_exe(argv[1])) {
        load_exe(argv[1]);
    } else {
        if (!pc_cd_open(argv[1])) {
            fprintf(stderr, "cannot open the disc image %s\n", argv[1]);
            usage();
        }
        if (argc > 2) {
            load_exe(argv[2]);
        } else {
            load_exe_from_disc("SCUS_942.44");
        }
    }
    patch_func_pointers();
    psx_start();
    return game_main();
}
