/* The start of the PC port: the memory of the PlayStation at its own
 * addresses, the user's executable loaded into it, then the game's main().
 *
 * The port is a 32-bit process. The 2 MB of RAM are at 0x80000000 and the
 * scratchpad (with the I/O ports after it) at 0x1F800000, where the code of
 * the game uses them: sections of the program (tools/pc/build.py) that the
 * system maps as zeroed memory. The global variables of the C files are linked
 * at their PlayStation addresses inside the RAM (tools/pc/build.py), so
 * loading the executable gives them their initial values, and the data that
 * is not C (the data segment: tables and pointers between them) is used in
 * place. Pointers to C functions in that data are PlayStation addresses: they
 * are replaced by the addresses of the x86 functions. */
#include "types.h"

#include <errno.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define RAM_ADDR 0x80000000u
#define RAM_SIZE 0x200000u

/* generated by tools/pc/build.py */
extern const u32 pc_func_table[][2];
extern const u32 pc_func_count;
extern const u32 pc_scan_ranges[][2];
extern const u32 pc_scan_count;

s32 game_main(void); /* main() of src/main.c */

static u32 func_lookup(u32 psx)
{
    u32 lo = 0, hi = pc_func_count;

    while (lo < hi) {
        u32 mid = (lo + hi) / 2;

        if (pc_func_table[mid][0] == psx) {
            return pc_func_table[mid][1];
        }
        if (pc_func_table[mid][0] < psx) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return 0;
}

static void load_exe(const char *path)
{
    FILE *f = fopen(path, "rb");
    u8 head[0x800];
    u32 t_addr, t_size;

    if (!f) {
        fprintf(stderr, "cannot open %s: %s\n(the port needs your SCUS_942.44, see disc/README.md)\n", path,
                strerror(errno));
        exit(1);
    }
    if (fread(head, 1, sizeof(head), f) != sizeof(head) || memcmp(head, "PS-X EXE", 8)) {
        fprintf(stderr, "%s is not a PlayStation executable\n", path);
        exit(1);
    }
    memcpy(&t_addr, head + 0x18, 4);
    memcpy(&t_size, head + 0x1C, 4);
    if (t_addr < RAM_ADDR || t_addr + t_size > RAM_ADDR + RAM_SIZE ||
        fread((void *)t_addr, 1, t_size, f) != t_size) {
        fprintf(stderr, "%s: bad executable\n", path);
        exit(1);
    }
    fclose(f);
}

/* pointers to C functions in the data: PlayStation addresses -> x86 */
static void patch_func_pointers(void)
{
    u32 i, n = 0;

    for (i = 0; i < pc_scan_count; i++) {
        u32 *p = (u32 *)pc_scan_ranges[i][0];
        u32 *end = (u32 *)pc_scan_ranges[i][1];

        for (; p < end; p++) {
            u32 x = func_lookup(*p);

            if (x) {
                *p = x;
                n++;
            }
        }
    }
    if (getenv("PC_VERBOSE")) {
        fprintf(stderr, "port: %u pointers to C functions in the data\n", n);
    }
}

/* the recompiled nd_asm: break, syscall, an unknown instruction */
void rc_trap(u32 addr, u32 what)
{
    fprintf(stderr, "port: trap at %08X (%08X) in the recompiled code\n", addr, what);
    abort();
}

int main(int argc, char **argv)
{
    const char *exe = argc > 1 ? argv[1] : "disc/SCUS_942.44";

    load_exe(exe);
    patch_func_pointers();
    return game_main();
}
