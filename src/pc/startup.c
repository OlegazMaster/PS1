/* The start of the PC port: the memory of the PlayStation at its own
 * addresses, the user's executable loaded into it, then the game's main().
 *
 * The port is a 32-bit process. The 2 MB of RAM are mapped at 0x80000000
 * and the scratchpad (with the I/O ports after it) at 0x1F800000, where the
 * code of the game uses them (on Windows a 32-bit program gets addresses
 * above 2 GB on a 64-bit system, as it is linked large address aware). The
 * global variables of the C files are at their PlayStation addresses inside
 * the RAM (tools/pc/build.py), so loading the executable gives them their
 * initial values, and the data that is not C (the data segment: tables and
 * pointers between them) is used in place. Pointers to C functions in that
 * data are PlayStation addresses: they are replaced by the addresses of the
 * x86 functions. */
#include "types.h"

#include <errno.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <dirent.h>
#ifndef _WIN32
#include <strings.h>
#endif

