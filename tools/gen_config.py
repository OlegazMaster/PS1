#!/usr/bin/env python3
"""Creates the initial splat configuration for a game executable.

Run once per version, after placing your own copy of the executable in disc/.
The generated config/<version>/splat.yaml is meant to be committed and then
refined by hand as file boundaries are discovered.

Usage: gen_config.py [--version us] [--exe disc/SCUS_942.44] [--force]
"""

import argparse
import sys
from pathlib import Path

import psexe
import versions

ROOT = Path(__file__).resolve().parent.parent


def find_sections(data: bytes):
    """Estimates where .text and .data start (file offsets, 0 if unknown).

    Uses splat's heuristic when splat is installed (tools/setup.sh does that).
    """
    try:
        from splat.util.psx.psxexeinfo import try_find_text
    except ImportError:
        print("предупреждение: splat не установлен (make setup), считаю, что код начинается с 0x800")
        return psexe.HEADER_SIZE, 0
    return try_find_text(data)


def render_yaml(version: str, info: versions.Version, exe: psexe.PsxExe,
                gp: int, text_start: int, data_start: int) -> str:
    def subsegment(offset: int, kind: str) -> str:
        return f"      - [0x{offset:X}, {kind}, \"{offset:X}\"]\n"

    subsegments = ""
    if text_start > psexe.HEADER_SIZE:
        subsegments += subsegment(psexe.HEADER_SIZE, "rodata")
    subsegments += subsegment(max(text_start, psexe.HEADER_SIZE), "asm").rstrip("\n") + " # estimated\n"
    if data_start:
        subsegments += subsegment(data_start, "data").rstrip("\n") + " # estimated\n"

    gp_line = f"  gp_value: 0x{gp:08X}\n" if gp else "  # gp_value: the executable does not set $gp\n"
    if exe.bss_size:
        bss_line = f"    # bss from the header: 0x{exe.bss_addr:08X} (+0x{exe.bss_size:X})\n"
    else:
        bss_line = "    # bss_size: fill in once the size of .bss is known\n"

    return f"""\
# splat configuration for {info.serial} ({info.region}).
# Generated by tools/gen_config.py, then maintained by hand: split the asm
# subsegments into c files as their boundaries are discovered.
name: {info.exe}
sha1: {exe.sha1}
options:
  basename: main
  base_path: ../..
  target_path: disc/{info.exe}
  elf_path: build/{version}/main.elf
  platform: psx
  compiler: PSYQ

  asm_path: asm/{version}
  src_path: src
  asset_path: assets/{version}
  build_path: build/{version}
  cache_path: asm/{version}/.splache
  ld_script_path: asm/{version}/main.ld
  undefined_funcs_auto_path: asm/{version}/undefined_funcs_auto.txt
  undefined_syms_auto_path: asm/{version}/undefined_syms_auto.txt
  symbol_addrs_path:
    - config/{version}/symbol_addrs.txt
  reloc_addrs_path:
    - config/{version}/reloc_addrs.txt

{gp_line}\
  find_file_boundaries: True
  # Keep asm for decompiled functions too: used by tools/progress.py and asm-differ.
  disassemble_all: True
  o_as_suffix: False
  use_legacy_include_asm: False
  migrate_rodata_to_functions: True
  section_order: [".rodata", ".text", ".data", ".bss"]
  subalign: 2

  string_encoding: ASCII
  data_string_encoding: ASCII
  rodata_string_guesser_level: 2
  data_string_guesser_level: 2

segments:
  - name: header
    type: header
    start: 0x0

  - name: main
    type: code
    start: 0x{psexe.HEADER_SIZE:X}
    vram: 0x{exe.load_addr:08X}
{bss_line}\
    subsegments:
{subsegments}\
  - [0x{exe.file_size:X}]
"""


def write_new(path: Path, contents: str):
    if not path.exists():
        path.write_text(contents, encoding="utf-8", newline="\n")
        print(f"создан {path.relative_to(ROOT)}")


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--version", default=versions.DEFAULT_VERSION)
    parser.add_argument("--exe", type=Path, help="defaults to disc/<executable name>")
    parser.add_argument("--force", action="store_true", help="overwrite an existing splat.yaml")
    args = parser.parse_args(argv[1:])

    info = versions.get(args.version)
    exe_path = args.exe or ROOT / "disc" / info.exe
    if not exe_path.exists():
        raise SystemExit(
            f"{exe_path} не найден: скопируйте {info.exe} из корня вашего диска "
            f"{info.serial} в папку disc/ (см. disc/README.md)"
        )

    try:
        data, exe = psexe.load(exe_path)
    except psexe.PsxExeError as e:
        raise SystemExit(f"{exe_path}: {e}")
    for problem in psexe.validate(exe):
        print(f"предупреждение: {problem}")
    if exe.region != info.region:
        print(f"предупреждение: файл от версии {exe.region}, а версия '{args.version}' — это {info.region}")

    config_dir = ROOT / "config" / args.version
    config_dir.mkdir(parents=True, exist_ok=True)
    yaml_path = config_dir / "splat.yaml"
    if yaml_path.exists() and not args.force:
        raise SystemExit(f"{yaml_path.relative_to(ROOT)} уже существует (перезаписать: --force)")

    text_start, data_start = find_sections(data)
    gp = psexe.find_gp(data, exe)
    yaml_path.write_text(render_yaml(args.version, info, exe, gp, text_start, data_start),
                         encoding="utf-8", newline="\n")
    print(f"записан {yaml_path.relative_to(ROOT)}")

    (config_dir / "checksum.sha1").write_text(
        f"{exe.sha1}  build/{args.version}/{info.exe}\n", encoding="utf-8", newline="\n")

    write_new(config_dir / "symbol_addrs.txt", "// Known symbols: name = 0xADDRESS; // type:func\n")
    write_new(config_dir / "reloc_addrs.txt", "")
    write_new(config_dir / "undefined_syms.txt",
              "/* Symbols outside of the executable (hardware registers, BIOS), linker script syntax. */\n")
    add_symbol(config_dir / "symbol_addrs.txt", "__SN_ENTRY_POINT", exe.entry)
    return 0


def add_symbol(path: Path, name: str, addr: int):
    text = path.read_text(encoding="utf-8")
    if f"{name} =" in text:
        return
    if text and not text.endswith("\n"):
        text += "\n"
    path.write_text(text + f"{name} = 0x{addr:08X}; // type:func\n", encoding="utf-8", newline="\n")
    print(f"{name} добавлен в {path.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main(sys.argv))
